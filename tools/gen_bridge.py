def emit_struct_decl(name: str, fields: list[Field], *, parse: bool, serialise: bool) -> list[str]:
    out = [f"struct {name} {{"]
    for field in fields:
        out += doc(field.summary, "  ")
        out.append(f"  {field.cpp_type} {field.name}{{}};")
    if fields:
        out.append("")
    if parse:
        out.append(f"  [[nodiscard]] static {name} FromJson(const nlohmann::json& value);")
    if serialise:
        out.append("  [[nodiscard]] nlohmann::json ToJson() const;")
    out += ["};", ""]
    return out


def emit_cpp_header(schema: Schema) -> str:
    out = [BANNER, "#pragma once", ""]
    out += [
        "#include <cstdint>",
        "#include <optional>",
        "#include <string>",
        "#include <string_view>",
        "#include <vector>",
        "",
        "#include <nlohmann/json.hpp>",
        "",
        "#include <sonora/bridge/capabilities.h>",
        "#include <sonora/bridge/protocol.h>",
        "",
        "namespace sonora::bridge {",
        "",
        f"inline constexpr int kProtocolVersion = {schema.protocol_version};",
        "",
    ]

    out += [
        "// Every capability this build knows about, in schema order. Generated so",
        "// that shell.getCapabilities cannot fall out of step with what is actually",
        "// implemented, and so that a required capability is required by",
        "// construction rather than by a runtime check someone can forget.",
        "inline constexpr CapabilityInfo kCapabilities[] = {",
    ]
    for cap in schema.capabilities:
        out.append(f'    {{"{cap.name}", {cap.version}, {cpp_bool(cap.required)}}},')
    out += ["};", ""]

    if schema.types:
        out += ["// Shared record types, declared once under \"types\" in the schema.", ""]
        for struct in schema.types:
            out += doc(f"{struct.name}: {struct.summary}")
            out += emit_struct_decl(struct.name, struct.fields, parse=True, serialise=True)

    for method in schema.methods:
        out += doc(f"{method.wire_name}: {method.summary}")
        out += emit_struct_decl(
            method.cpp_base + "Params", method.params, parse=True, serialise=False
        )
        out += emit_struct_decl(
            method.cpp_base + "Result", method.result, parse=False, serialise=True
        )

    for event in schema.events:
        out += doc(f"{event.wire_name} (event): {event.summary}")
        out += emit_struct_decl(
            event.cpp_base + "Event", event.payload, parse=False, serialise=True
        )

    out += [
        "// Implemented by the application. Pure virtual on purpose: a method added",
        "// to the schema stops the build here until someone handles it, which is a",
        "// better reminder than a runtime 'unknown method' nobody sees.",
        "//",
        "// A handler signals failure by throwing BridgeError. Dispatch catches it",
        "// and turns it into a typed response; nothing escapes into CEF.",
        "class BridgeHandlers {",
        " public:",
        "  virtual ~BridgeHandlers() = default;",
        "",
    ]
    for method in schema.methods:
        out += doc(f"{method.wire_name}", "  ")
        out.append(
            f"  virtual {method.cpp_base}Result {method.cpp_base}("
            f"const {method.cpp_base}Params& params) = 0;"
        )
        out.append("")
    out += [" protected:", "  BridgeHandlers() = default;", "};", ""]

    if schema.events:
        out += [
            "// The transport for events, implemented by the shell. Takes a name and a",
            "// payload because that is all a transport can know; nobody calls it",
            "// directly -- Events below is the door.",
            "class EventSink {",
            " public:",
            "  virtual ~EventSink() = default;",
            "",
            "  // coalesce: a pending event of the same name may be replaced by this",
            "  // one instead of both being delivered.",
            "  virtual void Emit(std::string_view name,",
            "                    const nlohmann::json& payload,",
            "                    bool coalesce) = 0;",
            "",
            " protected:",
            "  EventSink() = default;",
            "};",
            "",
            "// One method per event in the schema, so an event name is never spelled",
            "// out at a call site and cannot be typed wrong. Whether an event",
            "// coalesces is a property of the event, decided in the schema, not an",
            "// argument the caller passes differently from one place to the next.",
            "class Events {",
            " public:",
            "  explicit Events(EventSink& sink) : sink_(&sink) {}",
            "",
        ]
        for event in schema.events:
            out += doc(f"{event.wire_name}", "  ")
            out.append(
                f"  void {event.cpp_base}(const {event.cpp_base}Event& payload) const {{"
            )
            out.append(
                f'    sink_->Emit("{event.wire_name}", payload.ToJson(), '
                f"/*coalesce=*/{cpp_bool(event.coalesce)});"
            )
            out += ["  }", ""]
        out += [" private:", "  EventSink* sink_;", "};", ""]

    out += [
        "// Parses a request envelope, checks the capability is enabled, runs the",
        "// matching handler and serialises the answer. Never throws: every failure",
        "// comes back as a Response carrying an error code, because the caller is a",
        "// CEF callback that cannot handle one.",
        "[[nodiscard]] Response Dispatch(BridgeHandlers& handlers,",
        "                                const CapabilityRegistry& capabilities,",
        "                                std::string_view request_json);",
        "",
        "}  // namespace sonora::bridge",
        "",
    ]
    return "\n".join(out)


