# The agent's tool catalogue
# ---------------------------------------------------------------------------
#
# Two outputs from the same list, for the same reason the bridge has two: the native side
# needs a table it can validate against at compile time, and something has to be handed to a
# planner as text. Written by hand they would be one rename apart from disagreeing, and the
# way that failure shows up is a tool the validator has never heard of.


def emit_agent_json(schema: Schema) -> str:
    tools = [
        {
            "name": tool.name,
            "capability": tool.capability,
            "effect": tool.effect,
            "description": tool.summary,
            "parameters": tool.parameters,
        }
        for tool in schema.agent_tools
    ]
    document = {
        "$comment": [
            "Generated by tools/gen_bridge.py from schema/bridge.schema.json. Do not edit.",
            "",
            "The tools an agent may be told about, and nothing else the bridge can do. A",
            "method appears here because somebody wrote an \"agent\" block for it in the",
            "schema; the other methods of this bridge are not hidden from the planner as a",
            "precaution, they are absent from the only list the broker will validate",
            "against. See ADR 0016.",
            "",
            "effect \"read\"    -- run on sight: none of these can change or transmit anything",
            "effect \"confirm\" -- proposed, and run only after the person accepts the plan",
        ],
        "protocolVersion": schema.protocol_version,
        "tools": tools,
    }
    return json.dumps(document, indent=2) + "\n"


def emit_agent_cpp(schema: Schema, header_name: str) -> str:
    out = [
        "// Generated by tools/gen_bridge.py. Do not edit.",
        "//",
        "// The catalogue the broker validates every proposed call against. Generated, so that",
        "// removing an \"agent\" block from the schema removes the tool here in the same build",
        "// rather than the next time somebody remembers.",
        "",
        f'#include "{header_name}"',
        "",
        "namespace sonora::agent {",
        "namespace {",
        "",
        "// The JSON Schema for each tool's arguments, as text, because it is handed to a",
        "// planner and never inspected here. The broker validates against the typed field",
        "// list below it, not against this string.",
    ]
    for tool in schema.agent_tools:
        ident = tool.method.cpp_base
        params = json.dumps(tool.parameters, separators=(",", ":"))
        out.append(f'constexpr std::string_view k{ident}Parameters =')
        out.append(f'    R"json({params})json";')
    out += ["", "}  // namespace", ""]

    out += [
        "std::vector<Tool> GeneratedTools() {",
        "  std::vector<Tool> tools;",
        f"  tools.reserve({len(schema.agent_tools)});",
    ]
    for tool in schema.agent_tools:
        ident = tool.method.cpp_base
        effect = "Effect::kRead" if tool.effect == "read" else "Effect::kConfirm"
        out += [
            "  {",
            "    Tool tool;",
            f'    tool.name = "{tool.name}";',
            f'    tool.capability = "{tool.capability}";',
            f"    tool.effect = {effect};",
            f"    tool.description = {json.dumps(tool.summary)};",
            f"    tool.parameters_json = k{ident}Parameters;",
        ]
        for field in tool.method.params:
            out += [
                "    {",
                "      Parameter parameter;",
                f'      parameter.name = "{field.name}";',
                f"      parameter.type = ValueType::k{pascal(field.type)};",
                f"      parameter.array = {cpp_bool(field.array)};",
                f"      parameter.required = {cpp_bool(not field.optional)};",
                "      tool.parameters.push_back(parameter);",
                "    }",
            ]
        out += ["    tools.push_back(std::move(tool));", "  }"]
    out += ["  return tools;", "}", "", "}  // namespace sonora::agent", ""]
    return "\n".join(out)


