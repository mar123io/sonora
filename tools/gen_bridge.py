def write_if_changed(path: Path, text: str, label: str) -> None:
    if path.exists() and path.read_text(encoding="utf-8") == text:
        print(f"gen_bridge: {label} unchanged")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print(f"gen_bridge: wrote {label} -> {path}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schema", required=True, type=Path)
    parser.add_argument("--cpp-header", type=Path)
    parser.add_argument("--cpp-source", type=Path)
    parser.add_argument("--ts", type=Path)
    args = parser.parse_args()

    try:
        raw = json.loads(args.schema.read_text(encoding="utf-8"))
        schema = Schema(raw)
    except json.JSONDecodeError as error:
        print(f"gen_bridge: {args.schema} is not valid JSON: {error}", file=sys.stderr)
        return 1
    except SchemaError as error:
        print(f"gen_bridge: invalid schema: {error}", file=sys.stderr)
        return 1

    if args.cpp_source and not args.cpp_header:
        print("gen_bridge: --cpp-source needs --cpp-header for the include", file=sys.stderr)
        return 1

    if args.cpp_header:
        write_if_changed(args.cpp_header, emit_cpp_header(schema), "C++ header")
    if args.cpp_source:
        write_if_changed(args.cpp_source, emit_cpp_source(schema, args.cpp_header.name), "C++ source")
    if args.ts:
        write_if_changed(args.ts, emit_ts(schema), "TypeScript")

    print(
        f"gen_bridge: {len(schema.methods)} method(s) and {len(schema.events)} event(s) "
        f"across {len(schema.capabilities)} capability(ies), "
        f"{len(schema.types)} shared type(s)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
