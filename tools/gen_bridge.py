def emit_read(field: Field, indent: str = "  ") -> list[str]:
    """One field, read out of `value` into `out`."""
    quoted = f'"{field.name}"'
    if field.is_struct:
        reader = f"ReadStructArray<{field.type}>" if field.array else f"ReadStruct<{field.type}>"
    elif field.array:
        reader = f"ReadArray<{field.base_cpp}>"
    else:
        reader = f"ReadScalar<{field.base_cpp}>"
    call = f"{reader}(value.at({quoted}), {quoted})"

    if field.array:
        # An absent list is an empty list. Callers that care about the
        # difference should not be using an array.
        return [
            f"{indent}if (value.contains({quoted})) {{",
            f"{indent}  out.{field.name} = {call};",
            f"{indent}}}",
        ]
    if field.optional:
        return [
            f"{indent}if (value.contains({quoted}) && !value.at({quoted}).is_null()) {{",
            f"{indent}  out.{field.name} = {call};",
            f"{indent}}}",
        ]
    return [
        f"{indent}if (!value.contains({quoted})) {{",
        f"{indent}  throw BridgeError(ErrorCode::kInvalidParams,",
        f"{indent}                    \"missing required field '{field.name}'\");",
        f"{indent}}}",
        f"{indent}out.{field.name} = {call};",
    ]


def emit_write(field: Field, indent: str = "  ") -> list[str]:
    quoted = f'"{field.name}"'
    if field.is_struct and field.array:
        return [
            f"{indent}{{",
            f"{indent}  nlohmann::json items = nlohmann::json::array();",
            f"{indent}  for (const auto& item : {field.name}) {{",
            f"{indent}    items.push_back(item.ToJson());",
            f"{indent}  }}",
            f"{indent}  out[{quoted}] = std::move(items);",
            f"{indent}}}",
        ]
    if field.is_struct:
        return [f"{indent}out[{quoted}] = {field.name}.ToJson();"]
    if field.optional:
        return [
            f"{indent}if ({field.name}.has_value()) {{",
            f"{indent}  out[{quoted}] = *{field.name};",
            f"{indent}}}",
        ]
    return [f"{indent}out[{quoted}] = {field.name};"]


def emit_from_json(name: str, fields: list[Field], *, object_check: str) -> list[str]:
    out = [f"{name} {name}::FromJson(const nlohmann::json& value) {{"]
    if fields:
        out += [
            "  if (!value.is_object()) {",
            f'    throw BridgeError(ErrorCode::kInvalidParams, "{object_check}");',
            "  }",
        ]
    out.append(f"  {name} out;")
    for field in fields:
        out += emit_read(field)
    if not fields:
        out.append("  (void)value;  // nothing to read")
    out += ["  return out;", "}", ""]
    return out


def emit_to_json(name: str, fields: list[Field]) -> list[str]:
    out = [
        f"nlohmann::json {name}::ToJson() const {{",
        "  nlohmann::json out = nlohmann::json::object();",
    ]
    for field in fields:
        out += emit_write(field)
    out += ["  return out;", "}", ""]
    return out


def emit_cpp_source(schema: Schema, header_name: str) -> str:
    out = [BANNER, f'#include "{header_name}"', "", "namespace sonora::bridge {", ""]

    for struct in schema.types:
        out += emit_from_json(
            struct.name, struct.fields, object_check=f"{struct.name} must be an object"
        )
        out += emit_to_json(struct.name, struct.fields)

    for method in schema.methods:
        out += emit_from_json(
            method.cpp_base + "Params", method.params, object_check="params must be an object"
        )
        out += emit_to_json(method.cpp_base + "Result", method.result)

    for event in schema.events:
        out += emit_to_json(event.cpp_base + "Event", event.payload)

    out += [
        "Response Dispatch(BridgeHandlers& handlers,",
        "                  const CapabilityRegistry& capabilities,",
        "                  std::string_view request_json) {",
        "  std::string method;",
        "  try {",
        "    const Request request = Request::Parse(request_json);",
        "    method = request.method;",
        "",
    ]
    first = True
    for method in schema.methods:
        keyword = "if" if first else "} else if"
        first = False
        out.append(f'    {keyword} (request.method == "{method.wire_name}") {{')
        out.append(f'      capabilities.Require("{method.capability}");')
        out.append(f"      const auto params = {method.cpp_base}Params::FromJson(request.params);")
        out.append(f"      return Response::Ok(handlers.{method.cpp_base}(params).ToJson());")
    out += [
        "    } else {",
        "      throw BridgeError(ErrorCode::kUnknownMethod,",
        '                        "no such method: " + request.method);',
        "    }",
        "  } catch (const BridgeError& error) {",
        "    return Response::Failed(error.code(), error.what(), method);",
        "  } catch (const nlohmann::json::exception& error) {",
        "    return Response::Failed(ErrorCode::kInvalidParams, error.what(), method);",
        "  } catch (const std::exception& error) {",
        "    // A handler threw something of its own. The bridge must not take the",
        "    // process down over it, but it is a bug, not a protocol error.",
        "    return Response::Failed(ErrorCode::kInternalError, error.what(), method);",
        "  }",
        "}",
        "",
        "}  // namespace sonora::bridge",
        "",
    ]
    return "\n".join(out)


