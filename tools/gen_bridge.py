#!/usr/bin/env python3
"""Generate the native<->web bridge from schema/bridge.schema.json.

Emits three files from one description:

  * a C++ header  -- shared structs, request/response types, the handler
                     interface, the typed event emitter, dispatch
  * a C++ source  -- JSON parsing, serialisation and the dispatch table
  * a TypeScript  -- the same shapes, plus typed call wrappers and typed
                     event subscription

The point is not to save typing. It is that the two ends cannot drift: adding a
method to the schema makes the C++ fail to compile until a handler exists, and
gives the TypeScript the new signature in the same build. A hand-written bridge
drifts the first time someone renames a field on one side only, and the failure
surfaces at runtime in a message nobody reads.

The same argument applies to events, which is why they are generated too rather
than being "just a string and some JSON": an event name that does not exist is
a compile error on the native side and a type error in the page.

Usage:
    python tools/gen_bridge.py --schema schema/bridge.schema.json \\
        --cpp-header build/generated/bridge_generated.h \\
        --cpp-source build/generated/bridge_generated.cpp \\
        --ts ui/src/bridge/generated.ts
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

SCALARS = {
    #  schema      C++                TypeScript
    "string": ("std::string", "string"),
    "int": ("std::int64_t", "number"),
    "double": ("double", "number"),
    "bool": ("bool", "boolean"),
}

NAME_RE = re.compile(r"^[a-z][A-Za-z0-9]*$")

#  schema effect   what the broker does with a call to it
#  read            runs it, because none of these can change or send anything
#  confirm         proposes it, and runs it only once the person has accepted the plan
AGENT_EFFECTS = ("read", "confirm")

#  schema      JSON Schema
JSON_TYPES = {
    "string": "string",
    "int": "integer",
    "double": "number",
    "bool": "boolean",
}
TYPE_NAME_RE = re.compile(r"^[A-Z][A-Za-z0-9]*$")

BANNER = "// Generated by tools/gen_bridge.py from schema/bridge.schema.json.\n// Do not edit; edit the schema and rebuild.\n"


# ---------------------------------------------------------------------------
# Schema loading and validation
# ---------------------------------------------------------------------------


class SchemaError(Exception):
    pass


def pascal(name: str) -> str:
    return name[:1].upper() + name[1:]


class Field:
    def __init__(self, raw: dict, where: str, struct_names: set[str]):
        self.name = raw.get("name", "")
        if not NAME_RE.match(self.name):
            raise SchemaError(f"{where}: field name '{self.name}' must be lowerCamelCase")
        self.type = raw.get("type", "")
        self.is_struct = self.type in struct_names
        if not self.is_struct and self.type not in SCALARS:
            known = ", ".join(sorted(SCALARS) + sorted(struct_names))
            raise SchemaError(f"{where}.{self.name}: unknown type '{self.type}'; expected one of {known}")
        self.array = bool(raw.get("array", False))
        self.optional = bool(raw.get("optional", False))
        self.summary = raw.get("summary", "")
        if self.array and self.optional:
            # Allowed by the type system, but an absent list and an empty list
            # mean the same thing to every caller that has ever existed.
            raise SchemaError(f"{where}.{self.name}: use an empty array, not an optional array")
        if self.is_struct and self.optional:
            # Nothing needs it yet, and an optional struct doubles the parsing
            # paths. Left out until something actually asks for it.
            raise SchemaError(f"{where}.{self.name}: optional struct fields are not supported")

    @property
    def base_cpp(self) -> str:
        return self.type if self.is_struct else SCALARS[self.type][0]

    @property
    def cpp_type(self) -> str:
        if self.array:
            return f"std::vector<{self.base_cpp}>"
        if self.optional:
            return f"std::optional<{self.base_cpp}>"
        return self.base_cpp

    @property
    def ts_type(self) -> str:
        base = self.type if self.is_struct else SCALARS[self.type][1]
        return f"{base}[]" if self.array else base


class StructType:
    """A named record shared by several methods, declared under "types"."""

    def __init__(self, name: str, raw: dict, struct_names: set[str]):
        if not TYPE_NAME_RE.match(name):
            raise SchemaError(f"type '{name}' must be PascalCase")
        self.name = name
        self.summary = raw.get("summary", "")
        raw_fields = raw.get("fields", [])
        if not raw_fields:
            raise SchemaError(f"type '{name}' has no fields")
        # Structs hold scalars only. Nesting is a feature with no user yet, and
        # every level of it is another set of parse paths to get wrong.
        self.fields = [Field(f, f"types.{name}", set()) for f in raw_fields]
        _reject_duplicates(self.fields, f"type '{name}'")
        del struct_names


class Event:
    def __init__(self, raw: dict, capability: str, struct_names: set[str]):
        self.short_name = raw.get("name", "")
        where = f"{capability}.{self.short_name}"
        if not NAME_RE.match(self.short_name):
            raise SchemaError(f"{where}: event name must be lowerCamelCase")
        self.capability = capability
        self.wire_name = f"{capability}.{self.short_name}"
        self.summary = raw.get("summary", "")
        self.coalesce = bool(raw.get("coalesce", False))
        self.payload = [Field(f, f"{where}.payload", struct_names) for f in raw.get("payload", [])]
        _reject_duplicates(self.payload, where)

    @property
    def cpp_base(self) -> str:
        return pascal(self.capability) + pascal(self.short_name)


class Method:
    def __init__(self, raw: dict, capability: str, struct_names: set[str]):
        self.short_name = raw.get("name", "")
        where = f"{capability}.{self.short_name}"
        if not NAME_RE.match(self.short_name):
            raise SchemaError(f"{where}: method name must be lowerCamelCase")
        self.capability = capability
        self.wire_name = f"{capability}.{self.short_name}"
        self.summary = raw.get("summary", "")
        self.params = [Field(f, f"{where}.params", struct_names) for f in raw.get("params", [])]
        self.result = [Field(f, f"{where}.result", struct_names) for f in raw.get("result", [])]
        _reject_duplicates(self.params, where)
        _reject_duplicates(self.result, where)

        # An "agent" block is what exposes a method to the agent, and its absence is what
        # hides one. The default points that way on purpose: adding a tool costs a line
        # somebody wrote and had reviewed, forgetting one costs nothing. ADR 0016.
        self.agent = None
        raw_agent = raw.get("agent")
        if raw_agent is not None:
            if not isinstance(raw_agent, dict):
                raise SchemaError(f"{where}.agent: must be an object")
            effect = raw_agent.get("effect")
            if effect not in AGENT_EFFECTS:
                raise SchemaError(
                    f"{where}.agent.effect: must be one of {sorted(AGENT_EFFECTS)}, not {effect!r}")
            summary = raw_agent.get("summary", "")
            if not isinstance(summary, str) or len(summary) < 12:
                raise SchemaError(
                    f"{where}.agent.summary: an exposed tool needs a description written for a "
                    f"planner; the schema's own summary is design reasoning and is not one")
            unknown = set(raw_agent) - {"effect", "summary"}
            if unknown:
                raise SchemaError(f"{where}.agent: unknown key(s) {sorted(unknown)}")
            for field in self.params:
                # A struct argument would mean the planner composes one of this bridge's
                # types, and the validator would have to know all of them. Scalars and
                # arrays of scalars are what a tool call is allowed to be made of.
                if field.type not in SCALARS:
                    raise SchemaError(
                        f"{where}.agent: parameter '{field.name}' is a {field.type}; an exposed "
                        f"tool may only take scalars and arrays of scalars")
            self.agent = AgentTool(self, effect, summary)

    @property
    def cpp_base(self) -> str:
        return pascal(self.capability) + pascal(self.short_name)


class AgentTool:
    """One method as an agent sees it: a name, an effect class, and a parameter schema."""

    def __init__(self, method: "Method", effect: str, summary: str):
        self.method = method
        self.name = method.wire_name
        self.capability = method.capability
        self.effect = effect
        self.summary = summary

    @property
    def parameters(self) -> dict:
        """JSON Schema for the arguments, with additionalProperties closed.

        Closed because an open object is an invitation: a planner that adds a field nobody
        validates has found a way to say something the schema did not authorise, and the
        first time that matters it will not look like a security problem.
        """
        properties, required = {}, []
        for field in self.method.params:
            # The description goes on the parameter, not on both the array and its items:
            # saying it twice costs a planner tokens and tells it nothing.
            if field.array:
                properties[field.name] = {"type": "array",
                                          "items": {"type": JSON_TYPES[field.type]},
                                          "description": field.summary}
            else:
                properties[field.name] = {"type": JSON_TYPES[field.type],
                                          "description": field.summary}
            if not field.optional:
                required.append(field.name)
        return {"type": "object", "properties": properties,
                "required": required, "additionalProperties": False}


def _reject_duplicates(fields: list[Field], where: str) -> None:
    seen: set[str] = set()
    for field in fields:
        if field.name in seen:
            raise SchemaError(f"{where}: duplicate field '{field.name}'")
        seen.add(field.name)


class Capability:
    def __init__(self, raw: dict, struct_names: set[str]):
        self.name = raw.get("name", "")
        if not NAME_RE.match(self.name):
            raise SchemaError(f"capability name '{self.name}' must be lowerCamelCase")
        self.version = raw.get("version")
        if not isinstance(self.version, int) or self.version < 1:
            raise SchemaError(f"{self.name}: version must be an integer >= 1")
        self.required = bool(raw.get("required", False))
        self.summary = raw.get("summary", "")
        self.methods = [Method(m, self.name, struct_names) for m in raw.get("methods", [])]
        self.events = [Event(e, self.name, struct_names) for e in raw.get("events", [])]


class Schema:
    def __init__(self, raw: dict):
        self.protocol_version = raw.get("protocolVersion")
        if not isinstance(self.protocol_version, int):
            raise SchemaError("protocolVersion must be an integer")

        raw_types = raw.get("types", {})
        if not isinstance(raw_types, dict):
            raise SchemaError('"types" must be an object mapping a name to its fields')
        names = set(raw_types)
        self.types = [StructType(name, raw_types[name], names) for name in sorted(names)]

        self.capabilities = [Capability(c, names) for c in raw.get("capabilities", [])]
        if not self.capabilities:
            raise SchemaError("the schema defines no capabilities")
        if not any(cap.required for cap in self.capabilities):
            # Negotiation has to start somewhere. If every capability can be
            # switched off, so can the one that reports which are on.
            raise SchemaError("at least one capability must be marked \"required\"")

        # The agent's own capability may not be one of its tools. A planner that can call
        # agent.interpret is a planner that can call itself, and two rounds per sentence stops
        # being a bound on anything. Enforced here rather than trusted to whoever edits the
        # schema next, because the failure is a loop and not a compile error.
        for cap in self.capabilities:
            if cap.name != "agent":
                continue
            for method in cap.methods:
                if method.agent is not None:
                    raise SchemaError(
                        f"{method.wire_name}: the agent's own methods may not carry an \"agent\" "
                        f"block -- an agent that can call itself has no bound on its rounds")

        seen_caps: set[str] = set()
        seen_names: set[str] = set()
        for cap in self.capabilities:
            if cap.name in seen_caps:
                raise SchemaError(f"duplicate capability '{cap.name}'")
            seen_caps.add(cap.name)
            for item in [*cap.methods, *cap.events]:
                if item.wire_name in seen_names:
                    raise SchemaError(f"duplicate method or event '{item.wire_name}'")
                seen_names.add(item.wire_name)

    @property
    def methods(self) -> list[Method]:
        return [m for cap in self.capabilities for m in cap.methods]

    @property
    def events(self) -> list[Event]:
        return [e for cap in self.capabilities for e in cap.events]

    @property
    def agent_tools(self) -> list[AgentTool]:
        return [m.agent for m in self.methods if m.agent is not None]


