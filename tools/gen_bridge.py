def ts_doc(text: str, indent: str = "") -> list[str]:
    if not text:
        return []
    lines = _wrap(text, 72 - len(indent))
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    return [f"{indent}/**"] + [f"{indent} * {line}" for line in lines] + [f"{indent} */"]


def emit_ts_interface(name: str, fields: list[Field], summary: str = "") -> list[str]:
    out = ts_doc(summary)
    if not fields:
        return out + [f"export type {name} = Record<string, never>;", ""]
    out.append(f"export interface {name} {{")
    for field in fields:
        out += ts_doc(field.summary, "  ")
        optional = "?" if field.optional else ""
        out.append(f"  readonly {field.name}{optional}: {field.ts_type};")
    out += ["}", ""]
    return out


def emit_ts(schema: Schema) -> str:
    out = [
        BANNER.rstrip(),
        "",
        f"export const PROTOCOL_VERSION = {schema.protocol_version};",
        "",
    ]

    for struct in schema.types:
        out += emit_ts_interface(struct.name, struct.fields, struct.summary)

    out += [
        "/** A capability as the schema declares it, known at build time. */",
        "export interface DeclaredCapability {",
        "  readonly name: string;",
        "  readonly version: number;",
        "  readonly required: boolean;",
        "}",
        "",
        "/** What this build of the UI was compiled against. */",
        "export const DECLARED_CAPABILITIES: readonly DeclaredCapability[] = [",
    ]
    for cap in schema.capabilities:
        out.append(
            f"  {{ name: '{cap.name}', version: {cap.version}, "
            f"required: {str(cap.required).lower()} }},"
        )
    out += ["];", ""]

    for method in schema.methods:
        out += ts_doc(f"{method.wire_name}: {method.summary}")
        out += emit_ts_interface(method.cpp_base + "Params", method.params)
        out += emit_ts_interface(method.cpp_base + "Result", method.result)

    out.append("export interface MethodSignatures {")
    for method in schema.methods:
        out.append(
            f"  '{method.wire_name}': {{ params: {method.cpp_base}Params; "
            f"result: {method.cpp_base}Result }};"
        )
    out += ["}", ""]

    out += [
        "export type MethodName = keyof MethodSignatures;",
        "",
        "export const METHOD_NAMES: readonly MethodName[] = [",
    ]
    for method in schema.methods:
        out.append(f"  '{method.wire_name}',")
    out += ["];", ""]

    for event in schema.events:
        out += ts_doc(f"{event.wire_name}: {event.summary}")
        out += emit_ts_interface(event.cpp_base + "Event", event.payload)

    out.append("export interface EventPayloads {")
    for event in schema.events:
        out.append(f"  '{event.wire_name}': {event.cpp_base}Event;")
    if not schema.events:
        out.append("  [never: string]: never;")
    out += ["}", ""]

    out += ["export type EventName = keyof EventPayloads;", "", "export const EVENT_NAMES: readonly EventName[] = ["]
    for event in schema.events:
        out.append(f"  '{event.wire_name}',")
    out += ["];", ""]

    out += [
        "/** The transport. Supplied by invoke.ts so this file stays pure types. */",
        "export type InvokeFn = <M extends MethodName>(",
        "  method: M,",
        "  params: MethodSignatures[M]['params'],",
        ") => Promise<MethodSignatures[M]['result']>;",
        "",
        "/** Builds the typed API surface over a transport. */",
        "export function createApi(invoke: InvokeFn) {",
        "  return {",
    ]
    for cap in schema.capabilities:
        out.append(f"    {cap.name}: {{")
        for method in cap.methods:
            if method.params:
                out.append(f"      {method.short_name}: (params: {method.cpp_base}Params) =>")
                out.append(f"        invoke('{method.wire_name}', params),")
            else:
                out.append(f"      {method.short_name}: () =>")
                out.append(f"        invoke('{method.wire_name}', {{}}),")
        out.append("    },")
    out += ["  };", "}", "", "export type SonoraApi = ReturnType<typeof createApi>;", ""]
    return "\n".join(out)


